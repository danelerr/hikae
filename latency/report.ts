// Writes TESTNET.md and the results block of README.md from the latest testnet runs, so the documentation
// always matches the deployed contracts and the measured transactions.
// Usage: node latency/report.ts   (deploy.ps1 runs it at the end)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const latencyDir = join(root, "latency");

const env: Record<string, string> = Object.fromEntries(
  readFileSync(join(root, "deployments", "testnet.env"), "utf8")
    .split(/\r?\n/)
    .filter((line) => /^[A-Z0-9_]+=/.test(line))
    .map((line) => [line.slice(0, line.indexOf("=")), line.slice(line.indexOf("=") + 1)]),
);

const BASE = "https://sepolia.basescan.org";
const LASNA = "https://lasna.reactscan.net";
const UNI = "https://sepolia.uniscan.xyz";
const short = (hash: string) => `${hash.slice(0, 10)}…`;
const tx = (explorer: string, hash?: string) => (hash ? `[${short(hash)}](${explorer}/tx/${hash})` : "—");
const addr = (explorer: string, address?: string) => (address ? `[\`${address}\`](${explorer}/address/${address})` : "—");
const sourcify = (address?: string) => (address ? `[Sourcify](https://sourcify.dev/#/lookup/${address})` : "");
const pct = (pips: number) => `${(pips / 10000).toFixed(2)}%`;
const amount = (value: string) => Number(value).toFixed(5);
const seconds = (ms?: number) => (ms === undefined || ms === null ? "—" : `${(ms / 1000).toFixed(1)} s`);

function newest(prefix: string, accept: (data: any) => boolean) {
  const files = readdirSync(latencyDir)
    .filter((f) => f.startsWith(prefix) && f.endsWith(".json"))
    .sort()
    .reverse();
  for (const file of files) {
    const data = JSON.parse(readFileSync(join(latencyDir, file), "utf8"));
    if (accept(data)) return { file: `latency/${file}`, data };
  }
  return undefined;
}

// Only runs against the contracts deployed now count.
const latency = newest("results-", (d) => d.results?.length > 0 && !!d.results[0].uniTx);
const raceA = newest("race-", (d) => !!d.caseA);
const raceB = newest("race-", (d) => !!d.caseB);

const lines: string[] = [];
const now = new Date().toISOString().slice(0, 16).replace("T", " ");
lines.push("# Hikae on testnet", "");
lines.push(
  `Generated by \`latency/report.ts\` on ${now} UTC from \`deployments/testnet.env\`` +
    [latency?.file, raceA?.file, raceB?.file].filter((f, i, all) => f && all.indexOf(f) === i).map((f) => `, \`${f}\``).join("") +
    ".",
  "",
);

lines.push("## Contracts", "");
lines.push("| Contract | Chain | Address | Source |", "|---|---|---|---|");
lines.push(`| \`HikaeReactive\`, feeds the v1 hook | Reactive Lasna | ${addr(LASNA, env.REACTIVE)} | ${sourcify(env.REACTIVE)} |`);
lines.push(`| \`HikaeHook\` (v1, dynamic fee only) | Unichain Sepolia | ${addr(UNI, env.HOOK)} | ${sourcify(env.HOOK)} |`);
lines.push(`| \`HikaeReactive\`, feeds the retro hook | Reactive Lasna | ${addr(LASNA, env.RETRO_REACTIVE)} | ${sourcify(env.RETRO_REACTIVE)} |`);
lines.push(`| \`HikaeRetroHook\` | Unichain Sepolia | ${addr(UNI, env.RETRO_HOOK)} | ${sourcify(env.RETRO_HOOK)} |`);
lines.push(`| Demo router (\`MsgSenderRouter\`) | Unichain Sepolia | ${addr(UNI, env.DEMO_ROUTER)} | ${sourcify(env.DEMO_ROUTER)} |`);
lines.push(`| Reference pool (Uniswap v4 PoolManager) | Base Sepolia | ${addr(BASE, "0x05E73354cFDd6745C338b50BcFDfA3Aa6fA03408")} | pool id \`${env.REF_POOL_ID ?? "—"}\` |`);
lines.push("", "The Sourcify links show the verified source when the contracts were deployed with `deploy.ps1 -Verify`.", "");

if (latency) {
  const s = latency.data.summary;
  lines.push("## Full loop: Base → Lasna → Unichain", "");
  lines.push(
    `${s.delivered} of ${s.rounds} callbacks delivered. Each row is one loop: a swap on the Base Sepolia reference pool, ` +
      "the reactive transaction on Lasna that relayed it, and the callback on Unichain Sepolia. Latency runs from the " +
      "Base block (time computed on-chain from its number) to the start of the Unichain block that carried the callback.",
    "",
  );
  lines.push(
    `**p50 ${seconds(s.onchainLatencyMs?.p50)}, p95 ${seconds(s.onchainLatencyMs?.p95)}, max ${seconds(s.onchainLatencyMs?.max)}.**` +
      (s.baseToLasnaMs ? ` Base → Lasna p50 ${seconds(s.baseToLasnaMs.p50)}; Lasna → Unichain p50 ${s.lasnaToUnichainS?.p50 ?? "—"} s (whole-second block times).` : ""),
    "",
  );
  lines.push("| # | Swap on Base | Reactive tx on Lasna | Callback on Unichain | Base → Lasna | Lasna → Unichain | Total |", "|---|---|---|---|---|---|---|");
  for (const r of latency.data.results) {
    lines.push(
      `| ${r.round} | ${tx(BASE, r.baseTx)} | ${tx(LASNA, r.lasnaTx)} | ${tx(UNI, r.uniTx)} | ${seconds(r.baseToLasnaMs)} | ` +
        `${r.lasnaToUnichainS === undefined ? "—" : `${r.lasnaToUnichainS} s`} | ${seconds(r.onchainLatencyMs)} |`,
    );
  }
  lines.push("");
}

if (raceA) {
  const a = raceA.data.caseA;
  const r = a.retro;
  lines.push("## Race demo, case A: arbitrage ahead of the callback", "");
  lines.push(
    `Base moved (${tx(BASE, a.baseTx)}). The same 1-token swap then hit both Unichain pools before either callback ` +
      "landed. The v1 pool can only charge what it knows at swap time; the retro pool charges the rest once the " +
      "reference arrives.",
    "",
  );
  lines.push("| | v1 pool (`HikaeHook`) | Hikae pool (`HikaeRetroHook`) |", "|---|---|---|");
  lines.push(`| Swap | ${tx(UNI, a.v1.tx)} | ${tx(UNI, r.tx)} |`);
  lines.push(`| Fee paid at swap time | ${pct(a.v1.feePips)} | ${pct(r.feePaidPips)} |`);
  lines.push(`| Held | — | ${amount(r.held)} of ${amount(r.swapAmount)} |`);
  lines.push(`| Reactive tx on Lasna | — | ${tx(LASNA, r.reactiveTx)} |`);
  lines.push(`| Callback with the reference (${r.refTick}) | — | ${tx(UNI, r.callbackTx)}${r.settledByCallback ? ", which also settled the hold" : ""} |`);
  if (!r.settledByCallback) lines.push(`| Settlement | — | ${tx(UNI, r.settleTx)} |`);
  lines.push(`| **To LPs** | 0 | **${amount(r.toLPs)}** |`);
  lines.push(`| Refunded to the trader | — | ${amount(r.refund)} |`, "");
}

if (raceB) {
  const b = raceB.data.caseB;
  lines.push("## Race demo, case B: a swap before the move", "");
  lines.push(
    `A 1-token swap (${tx(UNI, b.swapTx)}) ran on the Hikae pool at block time ${b.swapBlockTime}. Base moved ` +
      `afterwards (${tx(BASE, b.baseTx)}, at ${(b.movedAtMs / 1000).toFixed(1)}). The reference was relayed ` +
      `(${tx(LASNA, b.reactiveTx)}) and landed ${tx(UNI, b.callbackTx)} at ${b.callbackLandedAt}, inside the window. ` +
      `Result: **${amount(b.toLPs)} to LPs, ${amount(b.refund)} refunded**. Why: ${b.reason}.`,
    "",
  );
}

writeFileSync(join(root, "TESTNET.md"), lines.join("\n"));

// README: a short block with the numbers and the links, between markers.
const block: string[] = ["<!-- testnet:start -->"];
if (latency) {
  const s = latency.data.summary;
  const first = latency.data.results.find((r: any) => r.lasnaTx) ?? latency.data.results[0];
  block.push(
    `- **Loop latency**, Base block to the Unichain block with the callback: p50 ${seconds(s.onchainLatencyMs?.p50)}, ` +
      `p95 ${seconds(s.onchainLatencyMs?.p95)}, ${s.delivered} of ${s.rounds} callbacks delivered. One loop: ` +
      `${tx(BASE, first.baseTx)} on Base → ${tx(LASNA, first.lasnaTx)} on Lasna → ${tx(UNI, first.uniTx)} on Unichain.`,
  );
}
if (raceA) {
  const a = raceA.data.caseA;
  block.push(
    `- **Arbitrage ahead of the callback**: the same swap paid ${pct(a.v1.feePips)} on the v1 pool and ` +
      `${pct(a.retro.feePaidPips)} on the Hikae pool, which then sent ${amount(a.retro.toLPs)} to its LPs` +
      `${a.retro.settledByCallback ? " in the callback itself" : ""} and refunded ${amount(a.retro.refund)}.`,
  );
}
if (raceB) {
  const b = raceB.data.caseB;
  block.push(`- **A swap before the move** got its whole hold back (${amount(b.refund)}).`);
}
block.push("- Every contract and transaction, with explorer links: [TESTNET.md](TESTNET.md).", "<!-- testnet:end -->");

const readmePath = join(root, "README.md");
const readme = readFileSync(readmePath, "utf8");
const start = readme.indexOf("<!-- testnet:start -->");
const end = readme.indexOf("<!-- testnet:end -->");
if (start >= 0 && end > start) {
  writeFileSync(readmePath, readme.slice(0, start) + block.join("\n") + readme.slice(end + "<!-- testnet:end -->".length));
}
console.log(`Wrote TESTNET.md and the README results block (${[latency, raceA, raceB].filter(Boolean).length} runs).`);
